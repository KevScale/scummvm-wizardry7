/**
 * Integration tests over the fixture *files* generated by
 * `tools/make_fixtures.py`.
 *
 * The suites in `parsers.h` build their input buffers inline, which never
 * exercises the `load(const Common::Path &)` entry points the engine uses
 * against real data. These tests read the committed fixtures from
 * `test/engines/wizardry7/fixtures/` (the build passes the directory as
 * `WIZ7_FIXTURE_DIR`) and assert the same decoded values, so a format change
 * has to update both.
 *
 * The fixtures are synthetic: no byte comes from a shipped game file.
 *
 * If the fixtures are missing the test warns and returns instead of failing;
 * CxxTest runs without exceptions here, so TS_SKIP would not stop the body.
 */
// kCharacterSize in save.cpp; not part of the public surface.
static const uint kFixtureCharacterSize = 584;

class Wizardry7FixtureTestSuite : public CxxTest::TestSuite {
public:
	void setUp() {
#if WIZ7_FIXTURES_AVAILABLE
		// FSNode/SearchMan need a backend; the fixture files are opened
		// through SearchMan exactly like the engine opens its data files.
		Common::install_null_g_system();
		ensureFixtureSearchPath();
#endif
	}

	void tearDown() {
#if WIZ7_FIXTURES_AVAILABLE
		Common::uninstall_null_g_system();
#endif
	}

	void testVgaBundleFile() {
		const Common::Path path = fixtureFile("vga_bundle.vga");
		if (!haveFixture(path))
			return;

		Wizardry7::VgaBundle bundle;
		TS_ASSERT(bundle.load(path));
		TS_ASSERT_EQUALS(bundle.getChunkCount(), 1u);
		TS_ASSERT_EQUALS(bundle.getRecordCount(), 1u);

		uint width, height;
		uint32 offset, size;
		TS_ASSERT(bundle.getChunkInfo(0, width, height, offset, size));
		TS_ASSERT_EQUALS(width, 8u);
		TS_ASSERT_EQUALS(height, 1u);
		TS_ASSERT_EQUALS(offset, 15u);
		TS_ASSERT_EQUALS(size, 8u);

		Wizardry7::VgaPlacement placement;
		TS_ASSERT(bundle.getPlacement(0, placement));
		TS_ASSERT_EQUALS(placement.bitmap, 3);
		TS_ASSERT_EQUALS(placement.x, -2);
		TS_ASSERT_EQUALS(placement.y, 4);
		TS_ASSERT_EQUALS(placement.xExtra, 5);
		TS_ASSERT_EQUALS(placement.rows, 6);
	}

	void testFontFile() {
		const Common::Path path = fixtureFile("font.vga");
		if (!haveFixture(path))
			return;

		Wizardry7::GameFont font;
		TS_ASSERT(font.load(path));
		TS_ASSERT_EQUALS(font.getWidth(), 2u);
		TS_ASSERT_EQUALS(font.getHeight(), 2u);
		TS_ASSERT_EQUALS(font.getGlyphCount(), 2u);
		TS_ASSERT_EQUALS(font.getAdvance(0), 1u);
		TS_ASSERT_EQUALS(font.getAdvance(1), 1u);
		TS_ASSERT_EQUALS(font.getAdvance(0x20), 0u);

		Graphics::Screen screen(4, 4);
		screen.fillRect(Common::Rect(4, 4), 0);
		TS_ASSERT_EQUALS(font.drawChar(1, &screen, 0, 0, 5, true, 0), 1u);
		TS_ASSERT_EQUALS(*(const byte *)screen.getBasePtr(0, 0), 0);
		TS_ASSERT_EQUALS(*(const byte *)screen.getBasePtr(1, 0), 5);
		TS_ASSERT_EQUALS(*(const byte *)screen.getBasePtr(0, 1), 5);
		TS_ASSERT_EQUALS(*(const byte *)screen.getBasePtr(1, 1), 0);
	}

	void testDosSaveFile() {
		const Common::Path path = fixtureFile("save_dos.sav");
		if (!haveFixture(path))
			return;

		Wizardry7::SaveGame save;
		TS_ASSERT(save.load(path));
		TS_ASSERT_EQUALS(save.getKind(), Wizardry7::kSaveDos);
		TS_ASSERT_EQUALS(save.getCharacterCount(), 1u);

		const Wizardry7::SaveCharacter &character = save.getCharacter(0);
		TS_ASSERT_EQUALS(character.name, Common::String("TEST"));
		TS_ASSERT_EQUALS(character.age, 7000u);
		TS_ASSERT_EQUALS(character.xp, 123u);
		TS_ASSERT_EQUALS(character.hp, 10u);
		TS_ASSERT_EQUALS(character.hpMax, 20u);
		TS_ASSERT_EQUALS(character.stamina, 30u);
		TS_ASSERT_EQUALS(character.ac, 7u);
		TS_ASSERT_EQUALS(character.level, 1u);
		TS_ASSERT_EQUALS(character.carryingCapacity, 50u);
		TS_ASSERT_EQUALS(character.gender, 1);
		TS_ASSERT_EQUALS(character.klass, 2);
		TS_ASSERT_EQUALS(character.alignment, 3);
		TS_ASSERT_EQUALS(character.stats[0], 12);
		TS_ASSERT_EQUALS(character.portrait, 12);
		TS_ASSERT_EQUALS(character.weaponry[0], 10);
		TS_ASSERT_EQUALS(character.inventoryCount[0], 1);

		TS_ASSERT_EQUALS(save.getPartyMaze(), 14);
		TS_ASSERT_EQUALS(save.getPartyX(), 56);
		TS_ASSERT_EQUALS(save.getPartyY(), 57);
		TS_ASSERT_EQUALS(save.getPartyLocalX(), 7);
		TS_ASSERT_EQUALS(save.getPartyLocalY(), 6);
		TS_ASSERT_EQUALS(save.getPartyWindow(), 5);
		TS_ASSERT_EQUALS(save.getPartyFacing(), 2);
		TS_ASSERT_EQUALS(save.getPrevMaze(), 14);
		TS_ASSERT_EQUALS(save.getPrevX(), 55);
		TS_ASSERT_EQUALS(save.getPartyCounter(), 1004);

		// Rewriting the character keeps every other byte of the container.
		byte replacement[kFixtureCharacterSize];
		memset(replacement, 0, sizeof(replacement));
		memcpy(replacement, "NEW", 3);
		replacement[0x18] = 5;
		TS_ASSERT(save.setCharacterRecord(0, replacement, sizeof(replacement)));
		TS_ASSERT_EQUALS(save.getCharacter(0).name, Common::String("NEW"));
		TS_ASSERT_EQUALS(save.getCharacter(0).hp, 5u);

		Common::Array<byte> written;
		TS_ASSERT(save.writeToData(written));
		Common::Array<byte> onDisk;
		TS_ASSERT(readFixture(path, onDisk));
		TS_ASSERT_EQUALS(written.size(), onDisk.size());
		TS_ASSERT_EQUALS(memcmp(written.data() + 10820, replacement, sizeof(replacement)), 0);
		TS_ASSERT_EQUALS(memcmp(written.data(), onDisk.data(), 10820), 0);
	}

	void testRosterFile() {
		const Common::Path path = fixtureFile("roster.pcf");
		if (!haveFixture(path))
			return;

		Wizardry7::CharacterRoster roster;
		TS_ASSERT(roster.load(path));
		TS_ASSERT_EQUALS(roster.getSlotCount(), 2u);
		TS_ASSERT(roster.isSlotUsed(0));
		TS_ASSERT(!roster.isSlotUsed(1));
		TS_ASSERT_EQUALS(roster.getCharacter(0).name, Common::String("AAA"));
		TS_ASSERT_EQUALS(roster.getCharacter(1).name, Common::String("BBB"));
		TS_ASSERT_EQUALS(roster.findFreeSlot(), 1);

		Common::Array<byte> onDisk;
		TS_ASSERT(readFixture(path, onDisk));

		byte record[kFixtureCharacterSize];
		memset(record, 0, sizeof(record));
		memcpy(record, "NEWCHAR12345", 12);
		record[0x238] = 1; // female
		TS_ASSERT(roster.setCharacterRecord(1, record, sizeof(record)));
		TS_ASSERT_EQUALS(roster.getCharacter(1).name, Common::String("NEWCHAR12345"));
		TS_ASSERT_EQUALS(roster.findFreeSlot(), -1);

		Common::Array<byte> written;
		TS_ASSERT(roster.writeToData(written));
		TS_ASSERT_EQUALS(written.size(), onDisk.size());
		TS_ASSERT_EQUALS(written[8 + 1], 1);
		TS_ASSERT_EQUALS(memcmp(written.data() + 24 + kFixtureCharacterSize, record, sizeof(record)), 0);
	}

	void testGoldMessageFiles() {
		const Common::Path headerPath = fixtureFile("msg_gold.hdr");
		const Common::Path poolPath = fixtureFile("msg_gold.gld");
		if (!haveFixture(headerPath) || !haveFixture(poolPath))
			return;

		Wizardry7::MessageDatabase messages;
		TS_ASSERT(messages.load(headerPath, poolPath));
		TS_ASSERT(!messages.isHuffmanCompressed());
		TS_ASSERT_EQUALS(messages.getEntryCount(), 2u);
		TS_ASSERT_EQUALS(messages.getFirstId(), 100);
		TS_ASSERT_EQUALS(messages.getLastId(), 200);
		TS_ASSERT_EQUALS(messages.getMessage(100), Common::String("ALPHA"));
		TS_ASSERT_EQUALS(messages.getMessage(101), Common::String("BETA"));
		TS_ASSERT_EQUALS(messages.getMessage(102), Common::String("GAMMA"));
		TS_ASSERT_EQUALS(messages.getMessage(200), Common::String("DELTA"));
		TS_ASSERT(!messages.hasMessage(103));
		TS_ASSERT(!messages.hasMessage(99));
	}

	void testDosMessageFiles() {
		const Common::Path headerPath = fixtureFile("msg_dos.hdr");
		const Common::Path poolPath = fixtureFile("msg_dos.dbs");
		const Common::Path huffmanPath = fixtureFile("misc.hdr");
		if (!haveFixture(headerPath) || !haveFixture(poolPath) || !haveFixture(huffmanPath))
			return;

		Wizardry7::MessageDatabase messages;
		TS_ASSERT(messages.load(headerPath, poolPath, huffmanPath));
		TS_ASSERT(messages.isHuffmanCompressed());
		TS_ASSERT_EQUALS(messages.getEntryCount(), 2u);
		TS_ASSERT_EQUALS(messages.getMessage(300), Common::String("ABCD"));
		TS_ASSERT_EQUALS(messages.getMessage(301), Common::String("ADCB"));
		TS_ASSERT_EQUALS(messages.getMessage(310), Common::String("CD"));
		TS_ASSERT(!messages.hasMessage(302));
	}

	void testScenarioDatabaseFiles() {
		const Common::Path masterPath = fixtureFile("master.hdr");
		const Common::Path diskPath = fixtureFile("disk.hdr");
		const Common::Path dataPath = fixtureFile("scenario.gld");
		if (!haveFixture(masterPath) || !haveFixture(diskPath) || !haveFixture(dataPath))
			return;

		Wizardry7::ScenarioDatabase scenario;
		TS_ASSERT(scenario.load(masterPath, diskPath, dataPath));
		TS_ASSERT_EQUALS(scenario.getRecordSize(Wizardry7::kRecordItem), 72);
		TS_ASSERT_EQUALS(scenario.getRecordSize(Wizardry7::kRecordMazeMain), 2768);
		TS_ASSERT_EQUALS(scenario.getRecordSize(Wizardry7::kRecordMonsterName), 232);
		TS_ASSERT_EQUALS(scenario.getRecordCount(Wizardry7::kRecordClassXP), 1u);
		TS_ASSERT_EQUALS(scenario.getRecordCount(Wizardry7::kRecordItem), 1u);
		TS_ASSERT_EQUALS(scenario.getRecordCount(Wizardry7::kRecordMazeMain), 1u);
		TS_ASSERT_EQUALS(scenario.getRecordCount(Wizardry7::kRecordMazeOverlay), 0u);
		TS_ASSERT_EQUALS(scenario.getRecordCount(Wizardry7::kRecordMonsterName), 1u);
		TS_ASSERT_EQUALS(scenario.getBaseOffset(Wizardry7::kRecordClassXP), 0u);
		TS_ASSERT_EQUALS(scenario.getBaseOffset(Wizardry7::kRecordItem), 64u);
		TS_ASSERT_EQUALS(scenario.getBaseOffset(Wizardry7::kRecordMazeMain), 136u);
		TS_ASSERT_EQUALS(scenario.getBaseOffset(Wizardry7::kRecordMonsterName), 2904u);

		// Type 0: experience thresholds for class 0.
		Common::Array<byte> record;
		TS_ASSERT(scenario.readRecord(Wizardry7::kRecordClassXP, 0, record));
		Wizardry7::ExperienceTable xp;
		TS_ASSERT(xp.parseRecord(record.data(), record.size(), 0));
		TS_ASSERT_EQUALS(xp.getThreshold(0, 1), 0u);
		TS_ASSERT_EQUALS(xp.getThreshold(0, 2), 1000u);
		TS_ASSERT_EQUALS(xp.getLevel(0, 1000), 2);
		TS_ASSERT_EQUALS(xp.getLevel(0, 2968000), 17);

		// Type 1: the item record parses through the scenario remap.
		TS_ASSERT(scenario.readRecord(Wizardry7::kRecordItem, 0, record));
		Wizardry7::ItemInfo item;
		TS_ASSERT(Wizardry7::parseItemRecord(record.data(), record.size(), item));
		TS_ASSERT_EQUALS(item.displayName, Common::String("SWORD OF FIRE"));
		TS_ASSERT_EQUALS(item.price, 0x1234);
		TS_ASSERT_EQUALS(item.weight, 0x012C);
		TS_ASSERT_EQUALS(item.damageDiceCount, 1);
		TS_ASSERT_EQUALS(item.damageDieSize, 6);
		TS_ASSERT_EQUALS(item.getSpellId(), 3);
		TS_ASSERT_EQUALS(item.getSpellPower(), 4);
		TS_ASSERT_EQUALS(item.kind, 0);
		TS_ASSERT_EQUALS(item.subtype, 2);
		TS_ASSERT_EQUALS(item.rank, 10);
		TS_ASSERT_EQUALS(item.acBonus, 2);

		// Type 2: MazeRecord reads the record through the database API.
		Wizardry7::MazeRecord maze;
		TS_ASSERT(maze.load(scenario, 0));
		TS_ASSERT_EQUALS(maze.getMonster(0, 0, 0), 0x12);
		TS_ASSERT_EQUALS(maze.getTileA(0), 3);
		TS_ASSERT_EQUALS(maze.getTileA(1), 5);
		TS_ASSERT_EQUALS(maze.getTileB(2), 6);
		TS_ASSERT_EQUALS(maze.getSpecial(1), 0x2A);
		TS_ASSERT_EQUALS(maze.getFlags(3), 2);
		TS_ASSERT(maze.getHazard(0, 9));
		TS_ASSERT_EQUALS(maze.getViewKind(0, 1, 1), 2);
		TS_ASSERT_EQUALS(maze.getEncounterGroup(0, false), 3);
		TS_ASSERT_EQUALS(maze.getEncounterGroup(0, true), 4);
		TS_ASSERT_EQUALS(maze.getEncounterChance(0), 65);

		// Type 4: the monster database loads from the same database.
		Wizardry7::MonsterDatabase monsters;
		TS_ASSERT(monsters.load(scenario));
		TS_ASSERT_EQUALS(monsters.getCount(), 1u);
		const Wizardry7::MonsterInfo &monster = monsters.getMonster(0);
		TS_ASSERT_EQUALS(monster.names[0], Common::String("DANDIPHOOT"));
		TS_ASSERT_EQUALS(monster.names[1], Common::String("DANDIPHOOTS"));
		TS_ASSERT_EQUALS(monster.xp, 390u);
		TS_ASSERT_EQUALS(monster.spawnCount, 5);
		TS_ASSERT_EQUALS(monster.levelDice, 0x020103u);
		TS_ASSERT_EQUALS(monster.actorCount, 2);
		TS_ASSERT_EQUALS(monster.hpDice, 0x0204u);
		TS_ASSERT_EQUALS(monster.stDice, 0x0104u);
		TS_ASSERT_EQUALS(monster.bodyType, 3);
		TS_ASSERT_EQUALS(monster.pictureId, 26);
		TS_ASSERT_EQUALS(monster.flags, 1);
	}

private:
	/** Fixture directory; the build bakes in the source tree path. */
	static Common::Path fixtureDirectory() {
#ifdef WIZ7_FIXTURE_DIR
		return Common::Path(WIZ7_FIXTURE_DIR);
#else
		return Common::Path("test/engines/wizardry7/fixtures");
#endif
	}

	/**
	 * Register the fixture directory with SearchMan, so a bare file name
	 * resolves the same way the engine resolves its own data files.
	 */
	static void ensureFixtureSearchPath() {
		Common::FSNode directory(fixtureDirectory());
		if (!directory.exists() || !directory.isDirectory())
			return;
		SearchMan.clear();
		SearchMan.addDirectory(fixtureDirectory(), 0, 1, false);
	}

	static Common::Path fixtureFile(const char *name) {
		return Common::Path(name);
	}

	static bool haveFixture(const Common::Path &path) {
		Common::File probe;
		if (probe.open(path))
			return true;
		TS_WARN(Common::String("fixture missing (run tools/make_fixtures.py): ") +
			fixtureDirectory().toString() + "/" + path.toString());
		return false;
	}

	static bool readFixture(const Common::Path &path, Common::Array<byte> &data) {
		Common::File file;
		if (!file.open(path))
			return false;
		const uint32 size = file.size();
		data.resize(size);
		return data.empty() || file.read(data.data(), size) == size;
	}
};

